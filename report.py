"""
report.py - Forensic PDF Report Generator.

This module generates professional, academic forensic examination reports in PDF format
using ReportLab. Reports include:
1. Header & Investigation Metadata.
2. Case Summary & Assigned Investigator.
3. Evidence Inventory (Filename, File size, Vendor, Format).
4. Cryptographic Hash & Integrity Status (SHA-256 original vs current).
5. Chain of Custody Activity History.
6. Forensic Principles & Limitations Statement.
"""

import os
from datetime import datetime
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable, KeepTogether
)
from database import (
    get_case_by_id, get_evidence_by_case, get_activity_logs, log_activity
)
from evidence import format_file_size

REPORTS_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'reports')
os.makedirs(REPORTS_DIR, exist_ok=True)


def generate_case_pdf_report(case_id, generated_by="Investigator"):
    """
    Generates a formal forensic examination PDF report for a given case.
    
    Returns:
        tuple: (pdf_path: str, filename: str) or (None, error_str)
    """
    case = get_case_by_id(case_id)
    if not case:
        return None, f"Case '{case_id}' not found."

    evidence_list = get_evidence_by_case(case_id)
    activity_logs = get_activity_logs(limit=30, case_id=case_id)

    timestamp_str = datetime.now().strftime("%Y%m%d_%H%M%S")
    pdf_filename = f"Forensic_Report_{case_id}_{timestamp_str}.pdf"
    pdf_path = os.path.join(REPORTS_DIR, pdf_filename)

    # Document setup
    doc = SimpleDocTemplate(
        pdf_path,
        pagesize=letter,
        leftMargin=36,
        rightMargin=36,
        topMargin=36,
        bottomMargin=36
    )

    styles = getSampleStyleSheet()
    
    # Custom styles
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=18,
        leading=22,
        textColor=colors.HexColor('#0f172a'),
        spaceAfter=4
    )
    
    subtitle_style = ParagraphStyle(
        'DocSubtitle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        leading=14,
        textColor=colors.HexColor('#475569'),
        spaceAfter=12
    )

    heading2_style = ParagraphStyle(
        'Heading2_Custom',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=12,
        leading=16,
        textColor=colors.HexColor('#1e3a8a'),
        spaceBefore=12,
        spaceAfter=6
    )

    body_style = ParagraphStyle(
        'Body_Custom',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9,
        leading=13,
        textColor=colors.HexColor('#1e293b')
    )

    hash_style = ParagraphStyle(
        'Hash_Custom',
        parent=styles['Normal'],
        fontName='Courier',
        fontSize=7,
        leading=9,
        textColor=colors.HexColor('#0f172a')
    )

    story = []

    # 1. Header Banner
    story.append(Paragraph("DIGITAL FORENSIC EXAMINATION REPORT", title_style))
    story.append(Paragraph("Multi-Vendor DVR/NVR Forensic Analysis Tool for CCTV Evidence", subtitle_style))
    story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor('#1e3a8a'), spaceAfter=12))

    # 2. Case Details Table
    story.append(Paragraph("1. Case Summary & Administrative Details", heading2_style))
    case_data = [
        [Paragraph("<b>Case ID:</b>", body_style), Paragraph(str(case['case_id']), body_style),
         Paragraph("<b>Date Created:</b>", body_style), Paragraph(str(case['created_at']), body_style)],
        [Paragraph("<b>Case Name:</b>", body_style), Paragraph(str(case['case_name']), body_style),
         Paragraph("<b>Case Status:</b>", body_style), Paragraph(str(case['status']), body_style)],
        [Paragraph("<b>Lead Investigator:</b>", body_style), Paragraph(str(case['investigator_name']), body_style),
         Paragraph("<b>Report Date:</b>", body_style), Paragraph(datetime.now().strftime("%Y-%m-%d %H:%M:%S"), body_style)],
        [Paragraph("<b>Description:</b>", body_style), Paragraph(str(case['description'] or 'N/A'), body_style),
         Paragraph("<b>Generated By:</b>", body_style), Paragraph(str(generated_by), body_style)]
    ]
    case_table = Table(case_data, colWidths=[100, 170, 100, 170])
    case_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#f8fafc')),
        ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor('#cbd5e1')),
        ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#e2e8f0')),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
    ]))
    story.append(case_table)
    story.append(Spacer(1, 10))

    # 3. Evidence Inventory Table
    story.append(Paragraph(f"2. Evidence Inventory ({len(evidence_list)} Items)", heading2_style))
    if evidence_list:
        ev_header = [
            Paragraph("<b>Evidence ID</b>", body_style),
            Paragraph("<b>Filename</b>", body_style),
            Paragraph("<b>Vendor</b>", body_style),
            Paragraph("<b>Size</b>", body_style),
            Paragraph("<b>Integrity Status</b>", body_style)
        ]
        ev_rows = [ev_header]
        for ev in evidence_list:
            status_color = "#15803d" if "Verified" in ev['integrity_status'] else "#b91c1c"
            status_p = Paragraph(f"<font color='{status_color}'><b>{ev['integrity_status']}</b></font>", body_style)
            ev_rows.append([
                Paragraph(str(ev['evidence_id']), body_style),
                Paragraph(str(ev['filename']), body_style),
                Paragraph(str(ev['vendor']), body_style),
                Paragraph(format_file_size(ev['file_size']), body_style),
                status_p
            ])
        ev_table = Table(ev_rows, colWidths=[90, 170, 90, 80, 110])
        ev_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#1e3a8a')),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor('#cbd5e1')),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#e2e8f0')),
        ]))
        story.append(ev_table)
    else:
        story.append(Paragraph("<i>No evidence files currently associated with this case.</i>", body_style))

    story.append(Spacer(1, 10))

    # 4. Cryptographic Hash Analysis & Verification Details
    story.append(Paragraph("3. Technical Analysis & Cryptographic Hash Details", heading2_style))
    if evidence_list:
        for idx, ev in enumerate(evidence_list, 1):
            tech_data = [
                [Paragraph("<b>Item #:</b>", body_style), Paragraph(str(idx), body_style),
                 Paragraph("<b>Source / Camera:</b>", body_style), Paragraph(str(ev['source'] or 'CCTV Source'), body_style)],
                [Paragraph("<b>Filename:</b>", body_style), Paragraph(str(ev['filename']), body_style),
                 Paragraph("<b>Format / Container:</b>", body_style), Paragraph(str(ev['file_type']), body_style)],
                [Paragraph("<b>Vendor ID:</b>", body_style), Paragraph(str(ev['vendor']), body_style),
                 Paragraph("<b>Date Acquired:</b>", body_style), Paragraph(str(ev['uploaded_at']), body_style)],
                [Paragraph("<b>Original SHA-256:</b>", body_style), Paragraph(str(ev['sha256_original']), hash_style),
                 Paragraph("", body_style), Paragraph("", body_style)],
                [Paragraph("<b>Current SHA-256:</b>", body_style), Paragraph(str(ev['sha256_current']), hash_style),
                 Paragraph("", body_style), Paragraph("", body_style)],
                [Paragraph("<b>Integrity Result:</b>", body_style),
                 Paragraph(f"<b>{ev['integrity_status']}</b>", body_style),
                 Paragraph("<b>Investigator Notes:</b>", body_style), Paragraph(str(ev['notes'] or 'None recorded.'), body_style)]
            ]
            t = Table(tech_data, colWidths=[100, 170, 100, 170])
            t.setStyle(TableStyle([
                ('SPAN', (1, 3), (3, 3)),
                ('SPAN', (1, 4), (3, 4)),
                ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#fcfcfc')),
                ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor('#94a3b8')),
                ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#f1f5f9')),
                ('TOPPADDING', (0, 0), (-1, -1), 3),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
            ]))
            story.append(KeepTogether([t, Spacer(1, 8)]))
    else:
        story.append(Paragraph("<i>No technical items to display.</i>", body_style))

    story.append(Spacer(1, 10))

    # 5. Chain of Custody & Audit Trail
    story.append(Paragraph("4. Chain of Custody & Activity History", heading2_style))
    if activity_logs:
        act_header = [
            Paragraph("<b>Timestamp</b>", body_style),
            Paragraph("<b>Action</b>", body_style),
            Paragraph("<b>Performed By</b>", body_style),
            Paragraph("<b>Details</b>", body_style)
        ]
        act_rows = [act_header]
        for act in activity_logs:
            act_rows.append([
                Paragraph(str(act['timestamp']), body_style),
                Paragraph(str(act['action']), body_style),
                Paragraph(str(act['performed_by']), body_style),
                Paragraph(str(act['details']), body_style)
            ])
        act_table = Table(act_rows, colWidths=[100, 100, 90, 250])
        act_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#334155')),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
            ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor('#cbd5e1')),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#e2e8f0')),
            ('TOPPADDING', (0, 0), (-1, -1), 3),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
        ]))
        story.append(KeepTogether([act_table]))
    else:
        story.append(Paragraph("<i>No activity logs recorded for this case.</i>", body_style))

    story.append(Spacer(1, 12))

    # 6. Forensic Limitations & Academic Compliance Statement
    story.append(Paragraph("5. Forensic Integrity Principles & Limitations", heading2_style))
    limitation_text = (
        "<b>Forensic Non-Destructive Principle:</b> All original evidence files are maintained in a secure, "
        "read-only directory. All examination, hashing, and analysis were performed on bit-exact working duplicates. "
        "<br/><b>SHA-256 Cryptographic Verification:</b> Integrities are validated using standard SHA-256 hashes. "
        "A match between acquisition hash and verification hash establishes proof that evidence has not been altered. "
        "<br/><b>Academic Prototype Scope:</b> Vendor identification is heuristic rule-based. Advanced proprietary "
        "DVR disk carving and low-level recovery of corrupt sectors are recognized as future enhancements."
    )
    story.append(Paragraph(limitation_text, body_style))

    # Build the document
    doc.build(story)

    # Log report generation activity
    log_activity(
        action="Report generated",
        details=f"Generated PDF forensic report '{pdf_filename}' for Case '{case_id}'.",
        case_id=case_id,
        performed_by=generated_by
    )

    return pdf_path, pdf_filename
